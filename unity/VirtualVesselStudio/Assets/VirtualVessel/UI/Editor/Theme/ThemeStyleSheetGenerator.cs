using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace VirtualVessel.UI.Editor.Theme
{
    /// <summary>
    /// Turns design tokens into USS text (UI foundation detailed design 7.1). Pure: no files and no
    /// AssetDatabase, so tests can compare its output with the committed stylesheets.
    /// </summary>
    internal static class ThemeStyleSheetGenerator
    {
        public const string CommonFileName = "tokens-common.uss";

        private const string Header = "/* Generated by ThemeGenerator from design-tokens.json. Do not edit by hand. */";

        public static string ThemeFileName(string paletteId, bool light)
        {
            return $"theme-{paletteId}-{(light ? "light" : "dark")}.uss";
        }

        public static string FontFileName(string fontSetId)
        {
            return $"fonts-{fontSetId.ToLowerInvariant()}.uss";
        }

        /// <summary>Every generated file name and its contents, in a stable order.</summary>
        public static IReadOnlyList<KeyValuePair<string, string>> Generate(DesignTokens tokens, IEnumerable<FontSetPaths> fontSets)
        {
            var files = new List<KeyValuePair<string, string>>
            {
                new KeyValuePair<string, string>(CommonFileName, Common(tokens)),
            };

            foreach (DesignTokens.PaletteToken palette in tokens.palettes)
            {
                files.Add(new KeyValuePair<string, string>(ThemeFileName(palette.id, light: false), Theme(tokens, palette, light: false)));
                files.Add(new KeyValuePair<string, string>(ThemeFileName(palette.id, light: true), Theme(tokens, palette, light: true)));
            }

            foreach (FontSetPaths fontSet in fontSets.OrderBy(f => f.Id, StringComparer.Ordinal))
            {
                files.Add(new KeyValuePair<string, string>(FontFileName(fontSet.Id), Fonts(tokens, fontSet)));
            }

            return files;
        }

        /// <summary>Every color variable of one palette and background, by token name without the prefix.</summary>
        public static IReadOnlyList<KeyValuePair<string, ThemeColor>> Colors(DesignTokens tokens, DesignTokens.PaletteToken palette, bool light)
        {
            var colors = new List<KeyValuePair<string, ThemeColor>>();
            var byName = new Dictionary<string, ThemeColor>(StringComparer.Ordinal);
            void Add(string name, ThemeColor color)
            {
                colors.Add(new KeyValuePair<string, ThemeColor>(name, color));
                byName[name] = color;
            }

            foreach (DesignTokens.NeutralToken neutral in tokens.neutrals)
            {
                int[] sl = light ? neutral.light : neutral.dark;
                Add(neutral.token, ThemeColor.FromHsl(palette.hue, sl[0], sl[1]));
            }

            ThemeColor primary = ThemeColor.FromHex(palette.primary);
            Add("primary", primary);
            Add("secondary", ThemeColor.FromHex(palette.secondary));

            // Pastel lines are too faint on light backgrounds, so light uses a deeper tone of the hue.
            Add("accent-line", light ? ThemeColor.FromHsl(palette.hue, tokens.accentLineLight[0], tokens.accentLineLight[1]) : primary);
            Add("glow", primary.WithAlpha(tokens.glowAlpha));
            Add("tint", primary.Mix(byName["surface"], tokens.tintAmount));
            Add("shadow", ThemeColor.FromHsl(palette.hue, tokens.shadow.saturation, tokens.shadow.lightness).WithAlpha(tokens.shadow.alpha));

            foreach (DesignTokens.StatusToken status in tokens.status)
            {
                ThemeColor color = ThemeColor.FromHex(light ? status.light : status.dark);
                Add(status.token, color);
                Add(status.token + "-soft", color.WithAlpha(status.softAlpha));
                Add(status.token + "-line", color.WithAlpha(tokens.statusLineAlpha));
            }

            Add("error-surface", byName["error"].Mix(byName["surface-2"], tokens.errorSurfaceAmount));
            return colors;
        }

        private static string Common(DesignTokens tokens)
        {
            var builder = new StringBuilder();
            builder.Append(Header).Append('\n');
            builder.Append('.').Append("vv-root").Append(" {\n");
            foreach (DesignTokens.SizeToken space in tokens.spacing)
            {
                builder.Append("    --vv-space-").Append(space.token).Append(": ").Append(space.px).Append("px;\n");
            }

            foreach (DesignTokens.SizeToken radius in tokens.radius)
            {
                builder.Append("    --vv-radius-").Append(radius.token).Append(": ").Append(radius.px).Append("px;\n");
            }

            builder.Append("}\n");
            foreach (DesignTokens.TypographyToken type in tokens.typography)
            {
                builder.Append("\n.vv-text-").Append(type.token).Append(" { font-size: ").Append(type.size).Append("px; }\n");
            }

            return builder.ToString();
        }

        private static string Theme(DesignTokens tokens, DesignTokens.PaletteToken palette, bool light)
        {
            var builder = new StringBuilder();
            builder.Append(Header).Append('\n');
            builder.Append("/* Palette: ").Append(palette.name).Append(", background: ").Append(light ? "light" : "dark").Append(". */\n");
            builder.Append(".vv-root {\n");
            foreach (KeyValuePair<string, ThemeColor> color in Colors(tokens, palette, light))
            {
                builder.Append("    --vv-color-").Append(color.Key).Append(": ").Append(color.Value.ToUss()).Append(";\n");
            }

            builder.Append("}\n");
            return builder.ToString();
        }

        private static string Fonts(DesignTokens tokens, FontSetPaths fontSet)
        {
            // Root text and each typography class map to one of the three files of the set. The
            // definition is reset so that -unity-font wins over the default theme's font asset.
            var byRole = new Dictionary<string, List<string>>(StringComparer.Ordinal)
            {
                ["regular"] = new List<string> { ".vv-root" },
                ["bold"] = new List<string>(),
                ["mono"] = new List<string>(),
            };

            foreach (DesignTokens.TypographyToken type in tokens.typography)
            {
                if (!byRole.TryGetValue(type.font, out List<string> selectors))
                {
                    throw new FormatException($"Typography '{type.token}' has unknown font role '{type.font}'.");
                }

                selectors.Add(".vv-text-" + type.token);
            }

            byRole["bold"].Add(".vv-bold");
            byRole["mono"].Add(".vv-mono");

            var builder = new StringBuilder();
            builder.Append(Header).Append('\n');
            builder.Append("/* Font set: ").Append(fontSet.Id).Append(". */\n");
            AppendFontRule(builder, byRole["regular"], fontSet.RegularPath);
            AppendFontRule(builder, byRole["bold"], fontSet.BoldPath);
            AppendFontRule(builder, byRole["mono"], fontSet.MonoPath);
            return builder.ToString();
        }

        private static void AppendFontRule(StringBuilder builder, IEnumerable<string> selectors, string assetPath)
        {
            builder.Append('\n').Append(string.Join(",\n", selectors)).Append(" {\n");
            builder.Append("    -unity-font: url(\"project://database/").Append(assetPath).Append("\");\n");
            builder.Append("    -unity-font-definition: initial;\n");
            builder.Append("}\n");
        }
    }

    /// <summary>Asset paths of a font set's files, as the generator needs them.</summary>
    internal readonly struct FontSetPaths
    {
        public FontSetPaths(string id, string regularPath, string boldPath, string monoPath)
        {
            Id = id;
            RegularPath = regularPath;
            BoldPath = boldPath;
            MonoPath = monoPath;
        }

        public string Id { get; }

        public string RegularPath { get; }

        public string BoldPath { get; }

        public string MonoPath { get; }
    }
}
